async def handle_build(
    goal: str,
    requirements: list[str],
    max_budget: float,
    push_to_github: bool = False,
    github_repo: str | None = None,
    serve: bool = False,
    port: int = 5000,
):
    """Executes full autonomous software engineering loop."""
    console.print(
        Panel.fit(
            f"[bold cyan]FORGE Engine[/bold cyan] -- Autonomous Software Synthesis\n[bold yellow]Goal:[/bold yellow] {goal}",
            title="Project FORGE",
        )
    )

    await db_manager.init_db()

    # Retrieve Persistent Long-Term Memory from Memora
    memory_context = ""
    try:
        from app.integrations.memora_client import get_memora_client

        memora = get_memora_client()
        memory_context = await memora.a_build_context_prompt(query=goal)
        if memory_context:
            console.print("[dim cyan][MEMORA] Recalled relevant cognitive memories and preferences for synthesis.[/dim cyan]")
    except Exception as e:
        logger.debug(f"Memora intake query failed: {e}")

    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        console=console,
    ) as progress:
        task_p = progress.add_task("[yellow]Intaking & Analyzing Task...", total=100)

        # 1. Intake & Plan
        task, graph = await orchestrator.intake_and_plan(
            goal=goal,
            requirements=requirements,
            mode=TaskMode.AUTONOMOUS,
            max_budget=max_budget,
            context={"memory_context": memory_context} if memory_context else None,
        )
        progress.update(
            task_p,
            advance=20,
            description="[cyan]8-Stage Plan Synthesized. Provisioning Workspace...",
        )

        # 2. Synthesize Initial Project Artifacts inside sandbox
        task_id = task.id
        paths = workspace_manager.get_workspace_paths(task_id)

        is_static_web = is_web_studio_goal(goal)

        if is_static_web:
            from app.templates.web_studio.generator import ForgeWebStudio

            studio_files = ForgeWebStudio.synthesize_website(goal, requirements)
            for rel_path, content in studio_files.items():
                workspace_manager.write_project_file(task_id, rel_path, content)
        else:
            workspace_manager.write_project_file(
                task_id,
                "main.py",
                (
                    '"""Generated by FORGE Autonomous Engine."""\n'
                    "import sys\n\n"
                    "def main():\n"
                    f'    print("Running: {goal}")\n'
                    "    return 0\n\n"
                    'if __name__ == "__main__":\n'
                    "    sys.exit(main())\n"
                ),
            )
            # The generated main.py defines `main()` only. The scaffolded test
            # used to import `build_parser`, which does not exist, so the very
            # first verification battery failed with an ImportError on every
            # non-web build.
            workspace_manager.write_project_file(
                task_id,
                "tests/test_main.py",
                (
                    "import pytest\n"
                    "from main import main\n\n"
                    "def test_main_returns_zero(capsys):\n"
                    "    assert main() == 0\n"
                    '    captured = capsys.readouterr()\n'
                    "    assert captured.out.strip() != ''\n\n"
                    "def test_main_is_callable():\n"
                    "    assert callable(main)\n"
                ),
            )

            workspace_manager.write_project_file(
                task_id,
                "README.md",
                f"# {goal}\n\nGenerated autonomously by Project FORGE.\n",
            )

        progress.update(
            task_p, advance=30, description="[blue]Executing TaskGraph & Specialist Agents..."
        )

        # 3. Step through Task Graph execution
        task = await orchestrator.run_task(task_id, max_iterations=10)

        progress.update(
            task_p, advance=25, description="[magenta]Running Objective Verification Battery..."
        )

        # 4. Objective Verification
        report = await verification_engine.verify_task(task_id)

        # 5. Debug / Recovery Loop if any verification check failed
        if not report.all_passed:
            progress.update(
                task_p, description="[red]Verification failed. Initiating Self-Repair & Debugger..."
            )
            any_recovered = False
            for ev in report.evidence:
                if not ev.passed:
                    recovered, msg, patch = await recovery_engine.attempt_recovery(task_id, ev)
                    if recovered:
                        any_recovered = True
                        console.print(f"[green][OK] Self-Repair succeeded:[/green] {msg}")
                    else:
                        console.print(f"[red][FAIL] Self-Repair warning:[/red] {msg}")
            if any_recovered:
                report = await verification_engine.verify_task(task_id)

        # Re-check task status from store to reflect accurate final state
        store = StateStore(db_manager)
        final_task = await store.get_task(task_id)
        if final_task:
            task = final_task

        paths = workspace_manager.get_workspace_paths(task_id)
        is_fallback = (
            (paths is not None and (paths.state / "FALLBACK_STUB.json").exists())
            or (task.error_message is not None and "fallback" in task.error_message.lower())
        )
        is_failed = task.state == TaskState.FAILED or is_fallback

        completion_desc = (
            "[red]Build Finished (Failed / Fallback Detected)"
            if is_failed
            else "[green]Build Complete & Checkpointed!"
        )
        progress.update(task_p, advance=25, description=completion_desc)

        # Record task lifecycle event to Memora persistent cognitive memory
        try:
            from app.integrations.memora_client import get_memora_client

            memora = get_memora_client()
            summary = f"Task {task_id} {task.state.value}. Passed {report.passed_checks}/{report.total_checks} verification checks."
            await memora.a_record_interaction(
                user_input=goal,
                agent_output=summary,
                agent_name="forge",
                event_type="software_build",
                tags=["forge_build", task.state.value, "verified" if report.all_passed else "unverified"],
                metadata={
                    "task_id": task_id,
                    "state": task.state.value,
                    "checks_passed": report.passed_checks,
                    "total_checks": report.total_checks,
                },
            )
        except Exception as e:
            logger.debug(f"Memora build record failed: {e}")

    # If fallback or failure occurred, print warning panel
    if is_fallback:
        console.print()
        console.print(
            Panel(
                "[bold white on red] TASK FAILED: Fell back to stub generation. Please check API keys and try again. [/bold white on red]",
                style="bold red",
                expand=False,
            )
        )
        console.print()
    elif is_failed:
        console.print()
        console.print(
            Panel(
                f"[bold white on red] TASK FAILED: {task.error_message or 'Execution encountered fatal error.'} [/bold white on red]",
                style="bold red",
                expand=False,
            )
        )
        console.print()
    elif not report.all_passed:
        console.print()
        console.print(
            f"[yellow]Notice:[/yellow] {report.passed_checks}/{report.total_checks} verification checks passed. Review report for minor advisories."
        )
        console.print()

    # Summary Report
    header_style = "bold red" if is_failed else "bold green"
    table = Table(
        title=f"Task Completion Report: {task_id}", show_header=True, header_style=header_style
    )
    table.add_column("Property", style="cyan")
    table.add_column("Value", style="white")

    table.add_row("Task ID", task.id)
    table.add_row("Goal", task.goal)
    table.add_row(
        "State",
        task.state.value,
        style="bold red" if task.state == TaskState.FAILED else "bold green",
    )
    table.add_row("Progress", f"{task.progress_percentage}%")
    table.add_row("Workspace Root", task.workspace_path)
    checks_color = "red" if not report.all_passed else "green"
    table.add_row(
        "Checks Passed",
        f"[{checks_color}]{report.passed_checks}/{report.total_checks}[/{checks_color}]",
    )
    console.print(table)

    # 6. Optional GitHub delivery. `push_to_github` / `github_repo` used to be
    # accepted by handle_build and then never read, so the CLI flags were silent
    # no-ops. Run the release engineer's branch -> commit -> push -> PR flow.
    if push_to_github:
        await _deliver_to_github(
            task_id=task_id,
            repo=github_repo,
            console=console,
        )

    if serve:
        await handle_serve(task_id=task_id, port=port, open_browser=True)

    return task


async def _deliver_to_github(task_id: str, repo: str | None, console) -> None:
    """Branch, commit, push and open a PR for a completed task (best effort)."""
    from app.execution.github import GitHubTool

    github = GitHubTool()
    branch = f"forge/{task_id}"

    try:
        branch_res = await github.create_branch(task_id, branch, role="release_engineer")
        if branch_res.get("status") != "success":
            console.print(
                f"[red][FAIL] Could not create branch '{branch}': "
                f"{branch_res.get('stderr', 'unknown error')}[/red]"
            )
            return

        commit_res = await github.commit_files(
            task_id, f"FORGE autonomous delivery for {task_id}", role="release_engineer"
        )
        if commit_res.get("status") != "success":
            console.print("[red][FAIL] Commit failed; aborting delivery.[/red]")
            return

        push_ok = await github.git.push(
            task_id, branch=branch, role="release_engineer", authorized=True
        )
        if not push_ok:
            console.print(
                "[red][FAIL] Push failed (no remote or credentials?). "
                "Configure GITHUB_TOKEN and a git remote, then retry.[/red]"
            )
            return

        pr = await github.git.create_pr(
            task_id,
            title=f"FORGE delivery: {task_id}",
            body="Automated pull request generated by the FORGE autonomous engine.",
            head_branch=branch,
            base_branch="main",
            role="release_engineer",
            authorized=True,
        )
        if "mock-repo" in pr.get("pr_url", ""):
            console.print(
                "[yellow][WARN] Push succeeded but no PR could be opened "
                "(no GitHub token/repo configured).[/yellow]"
            )
        else:
            console.print(f"[green][OK] Pull request opened:[/green] {pr['pr_url']}")
    except Exception as e:
        logger.error(f"GitHub delivery failed for task {task_id}: {e}")
        console.print(f"[red][FAIL] GitHub delivery failed:[/red] {e}")


async def handle_serve(task_id: str, port: int = 5000, open_browser: bool = True):
    """Serve a project workspace on localhost with auto-discovery of entrypoint."""
    import http.server
    import os
    import socketserver
    import webbrowser

    await db_manager.init_db()
    if task_id == "latest":
        store = StateStore(db_manager)
        tasks = await store.list_tasks(limit=1)
        if not tasks:
            console.print("[red]Error:[/red] No tasks found in database.")
            return
        task_id = tasks[0].id

    paths = workspace_manager.get_workspace_paths(task_id)
    if not paths or not paths.project.exists():
        console.print(f"[red]Error:[/red] Workspace project directory for '{task_id}' not found.")
        return

    project_dir = str(paths.project)
    # This used to be a bare expression statement whose result was discarded --
    # dead code that looked like a discovery check but did nothing.
    has_index_html = (paths.project / "index.html").exists()
    html_files = list(paths.project.glob("**/*.html"))
    has_fastapi = (paths.project / "main.py").exists() and "fastapi" in (
        paths.project / "main.py"
    ).read_text(encoding="utf-8", errors="ignore").lower()

    console.print()
    console.print(
        Panel.fit(
            f"[bold green]Starting Localhost Server for Task:[/bold green] [cyan]{task_id}[/cyan]\n"
            f"[bold yellow]Directory:[/bold yellow] {project_dir}\n"
            f"[bold magenta]URL:[/bold magenta] [underline blue]http://localhost:{port}[/underline blue]\n\n"
            f"[dim]Press Ctrl+C to stop the server[/dim]",
            title="FORGE Local Deployment",
        )
    )

    if open_browser:
        # Open the browser only once the server is actually listening: opening it
        # before uvicorn/serve_forever starts produced a connection-refused page.
        import threading

        def _open_when_ready() -> None:
            import socket
            import time as _time

            for _ in range(100):
                try:
                    with socket.create_connection(("127.0.0.1", port), timeout=0.25):
                        break
                except OSError:
                    _time.sleep(0.1)
            try:
                webbrowser.open(f"http://localhost:{port}")
            except Exception:
                pass

        threading.Thread(target=_open_when_ready, daemon=True).start()

    if has_fastapi:
        # Launch Uvicorn server for FastAPI backend
        import sys

        import uvicorn

        sys.path.insert(0, project_dir)
        # Restore the previous working directory when the server exits; the old
        # code chdir'd and never came back, corrupting every later relative path.
        original_cwd = os.getcwd()
        os.chdir(project_dir)
        try:
            uvicorn.run("main:app", host="127.0.0.1", port=port, log_level="info")
        except Exception as e:
            console.print(
                f"[yellow]FastAPI uvicorn startup failed ({e}). Falling back to static HTTP server...[/yellow]"
            )
            has_fastapi = False
        finally:
            os.chdir(original_cwd)

    if not has_fastapi:
        # Standard HTTP static web server.
        # Bind to loopback: TCPServer(("", port)) listens on every interface,
        # exposing the generated project to the whole network while the banner
        # promised localhost.
        original_cwd = os.getcwd()
        os.chdir(project_dir)
        handler = http.server.SimpleHTTPRequestHandler
        try:
            with socketserver.TCPServer(("127.0.0.1", port), handler) as httpd:
                console.print(
                    f"[bold green][OK] Serving live on http://localhost:{port} "
                    f"(loopback only)[/bold green]"
                    + ("" if (has_index_html or html_files) else " -- no HTML entrypoint found")
                )
                httpd.serve_forever()
        except KeyboardInterrupt:
            console.print("\n[yellow]Server stopped by user.[/yellow]")
        except Exception as e:
            console.print(f"[red]Error starting server on port {port}:[/red] {e}")
        finally:
            os.chdir(original_cwd)


async def handle_status(task_id: str):
    """Display task progress and state."""
    await db_manager.init_db()
    store = StateStore(db_manager)
    task = await store.get_task(task_id)

    if not task:
        console.print(f"[red]Error:[/red] Task '{task_id}' not found.")
        return

    table = Table(title=f"Status: {task_id}", show_header=True, header_style="bold cyan")
    table.add_column("Metric", style="yellow")
    table.add_column("Details", style="white")

    table.add_row("Goal", task.goal)
    table.add_row("State", task.state.value)
    table.add_row("Progress", f"{task.progress_percentage}%")
    table.add_row("Budget Used", f"${task.budget_consumed:.4f} / ${task.max_budget:.2f}")
    table.add_row("Created At", task.created_at.strftime("%Y-%m-%d %H:%M:%S UTC"))
    table.add_row("Updated At", task.updated_at.strftime("%Y-%m-%d %H:%M:%S UTC"))

    console.print(table)


async def handle_logs(task_id: str, lines_count: int = 40):
    """Display recent logs for a task."""
    paths = workspace_manager.get_workspace_paths(task_id)
    if not paths or not paths.logs.exists():
        console.print(f"[red]Error:[/red] Workspace logs for task '{task_id}' not found.")
        return

    log_files = list(paths.logs.glob("*.log"))
    if not log_files:
        console.print(f"[yellow]No log files found in {paths.logs}[/yellow]")
        return

    for lf in log_files:
        console.print(f"[bold cyan]--- {lf.name} ---[/bold cyan]")
        text = lf.read_text(encoding="utf-8", errors="replace")
        tail = "\n".join(text.splitlines()[-lines_count:])
        console.print(tail if tail.strip() else "[dim](empty)[/dim]")


async def handle_pause(task_id: str, reason: str):
    """Pause a running task."""
    await db_manager.init_db()
    store = StateStore(db_manager)
    lifecycle = TaskStateMachine(store)
    try:
        updated, cp = await lifecycle.pause(task_id=task_id, reason=reason)
        console.print(
            f"[green][OK] Task '{task_id}' paused successfully.[/green] Checkpoint ID: [cyan]{cp.id}[/cyan]"
        )
    except Exception as e:
        console.print(f"[red]Error pausing task:[/red] {e}")


async def handle_resume(task_id: str, reason: str):
    """Resume a paused task."""
    await db_manager.init_db()
    store = StateStore(db_manager)
    lifecycle = TaskStateMachine(store)
    try:
        updated, cp = await lifecycle.resume(task_id=task_id, reason=reason)
        console.print(
            f"[green][OK] Task '{task_id}' resumed successfully.[/green] Restored from checkpoint: [cyan]{cp.id if cp else 'None'}[/cyan]"
        )
    except Exception as e:
        console.print(f"[red]Error resuming task:[/red] {e}")


async def handle_cancel(task_id: str, reason: str):
    """Cancel a task."""
    await db_manager.init_db()
    store = StateStore(db_manager)
    lifecycle = TaskStateMachine(store)
    try:
        await lifecycle.cancel(task_id=task_id, reason=reason)
        console.print(f"[yellow][!] Task '{task_id}' cancelled successfully.[/yellow]")
    except Exception as e:
        console.print(f"[red]Error cancelling task:[/red] {e}")


async def handle_inspect(task_id: str):
    """Deep inspect task state, graph nodes, checkpoints, and artifacts."""
    await db_manager.init_db()
    store = StateStore(db_manager)
    task = await store.get_task(task_id)

    if not task:
        console.print(f"[red]Error:[/red] Task '{task_id}' not found.")
        return

    graph = await store.get_latest_task_graph_for_project(task_id)
    checkpoints = await store.list_checkpoints(task_id)
    events = await store.get_audit_trail(task_id)
    artifacts = await store.list_artifacts_for_task(task_id)

    console.print(
        Panel(
            f"[bold cyan]Task ID:[/bold cyan] {task.id}\n[bold yellow]Goal:[/bold yellow] {task.goal}\n[bold magenta]State:[/bold magenta] {task.state.value} ({task.progress_percentage}%)\n[bold green]Sandbox:[/bold green] {task.workspace_path}",
            title="Task Inspection",
        )
    )

    # Nodes Table
    if graph and graph.nodes:
        table = Table(title="Task Graph Nodes", show_header=True, header_style="bold magenta")
        table.add_column("Title", style="white")
        table.add_column("Stage", style="cyan")
        table.add_column("Agent", style="yellow")
        table.add_column("Status", style="green")

        for node in graph.nodes.values():
            table.add_row(
                node.title,
                str(node.metadata.get("stage", "Unknown")),
                str(node.assigned_agent or "developer"),
                node.status.value,
            )
        console.print(table)

    console.print(
        f"[cyan]Checkpoints:[/cyan] {len(checkpoints)} | [cyan]Audit Events:[/cyan] {len(events)} | [cyan]Artifacts:[/cyan] {len(artifacts)}"
    )


def main():
    """Main CLI entry point for FORGE."""
    parser = argparse.ArgumentParser(
        prog="forge",
        description="FORGE: Autonomous Software Engineering Engine CLI",
    )
    subparsers = parser.add_subparsers(dest="command", help="Command to execute")

    # forge build
    build_parser = subparsers.add_parser(
        "build", help="Autonomously synthesize and verify a software goal"
    )
    build_parser.add_argument("goal", type=str, help="High-level engineering goal")
    build_parser.add_argument(
        "--req", "-r", action="append", default=[], help="Explicit constraint or requirement"
    )
    build_parser.add_argument("--budget", "-b", type=float, default=10.0, help="Max budget in USD")
    build_parser.add_argument(
        "--push-to-github",
        "-p",
        action="store_true",
        default=False,
        help="Push delivery branch to GitHub and open a Pull Request",
    )
    build_parser.add_argument(
        "--github-repo",
        "--repo",
        type=str,
        default=None,
        help="Target GitHub repository (e.g. owner/repo)",
    )
    build_parser.add_argument(
        "--serve",
        "-s",
        action="store_true",
        default=False,
        help="Automatically serve the generated project on localhost after build",
    )
    build_parser.add_argument(
        "--port", type=int, default=5000, help="Localhost port to serve on (default: 5000)"
    )

    # forge serve
    serve_parser = subparsers.add_parser(
        "serve", help="Serve a built project workspace on localhost"
    )
    serve_parser.add_argument("task_id", type=str, help="Task ID or latest")
    serve_parser.add_argument(
        "--port", type=int, default=5000, help="Port to bind server (default: 5000)"
    )
    serve_parser.add_argument(
        "--open-browser", "-o", action="store_true", default=True, help="Automatically open browser"
    )

    # forge status
    status_parser = subparsers.add_parser("status", help="Inspect task status and progress")
    status_parser.add_argument("task_id", type=str, help="Task ID")

    # forge logs
    logs_parser = subparsers.add_parser("logs", help="Display workspace terminal and agent logs")
    logs_parser.add_argument("task_id", type=str, help="Task ID")
    logs_parser.add_argument("--lines", "-n", type=int, default=40, help="Lines of logs to show")

    # forge pause
    pause_parser = subparsers.add_parser("pause", help="Pause a running task and checkpoint state")
    pause_parser.add_argument("task_id", type=str, help="Task ID")
    pause_parser.add_argument(
        "--reason", type=str, default="User requested pause", help="Reason for pause"
    )

    # forge resume
    resume_parser = subparsers.add_parser(
        "resume", help="Resume a paused task from latest checkpoint"
    )
    resume_parser.add_argument("task_id", type=str, help="Task ID")
    resume_parser.add_argument(
        "--reason", type=str, default="User requested resume", help="Reason for resume"
    )

    # forge cancel
    cancel_parser = subparsers.add_parser("cancel", help="Cancel task execution")
    cancel_parser.add_argument("task_id", type=str, help="Task ID")
    cancel_parser.add_argument(
        "--reason", type=str, default="User requested cancel", help="Reason for cancel"
    )

    # forge inspect
    inspect_parser = subparsers.add_parser(
        "inspect", help="Deep inspection of task graph and audit trail"
    )
    inspect_parser.add_argument("task_id", type=str, help="Task ID")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        sys.exit(1)

    if args.command == "build":
        # handle_build returns the final TaskEntity. Its return value used to be
        # discarded, so a task that ended FAILED -- including the fallback-stub
        # path -- still exited 0 and any CI job running `forge build` reported
        # success. The build outcome is now the process exit code.
        built_task = asyncio.run(
            handle_build(
                goal=args.goal,
                requirements=args.req,
                max_budget=args.budget,
                push_to_github=args.push_to_github,
                github_repo=args.github_repo,
                serve=args.serve,
                port=args.port,
            )
        )
        sys.exit(
            0
            if built_task is not None and built_task.state == TaskState.COMPLETED
            else 1
        )
    elif args.command == "serve":
        asyncio.run(handle_serve(args.task_id, args.port, args.open_browser))
    elif args.command == "status":
        asyncio.run(handle_status(args.task_id))
    elif args.command == "logs":
        asyncio.run(handle_logs(args.task_id, args.lines))
    elif args.command == "pause":
        asyncio.run(handle_pause(args.task_id, args.reason))
    elif args.command == "resume":
        asyncio.run(handle_resume(args.task_id, args.reason))
    elif args.command == "cancel":
        asyncio.run(handle_cancel(args.task_id, args.reason))
    elif args.command == "inspect":
        asyncio.run(handle_inspect(args.task_id))


if __name__ == "__main__":
    main()
